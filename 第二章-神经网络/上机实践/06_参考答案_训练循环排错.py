print('''
【错误 1】backward 与 step 顺序写反

    optimizer.zero_grad()
    logits = model(X_train)
    loss = loss_fn(logits, y_train)
    optimizer.step()        # ← 先更新了
    loss.backward()         # ← 后算梯度

答案：A —— 等于拿上一步的旧梯度更新参数，这一步白更新。
      step() 用的是 optimizer 里当前存的梯度；此时梯度还没算出来，
      用的是上一批遗留的值（甚至是 0）。而且这一批的梯度算出来后，
      因为已经 step 过，也没有被用上，训练会变得混乱、收敛变慢甚至不收敛。

      ★ 口诀：zero_grad → forward → loss → backward → step，一步都不能换位。

--------------------------------------------------------------------------
【错误 2】忘记 optimizer.zero_grad()

答案：B —— 梯度会逐批累加，loss 曲线剧烈震荡、难以收敛。
      PyTorch 的梯度是“累加”的（+ = ），不是“覆盖”。
      batch1 的梯度会留在 .grad 里，batch2 再 += 上去，越滚越大，
      相当于学习率被不断放大 —— 典型现象就是 loss 上下乱跳。

--------------------------------------------------------------------------
【错误 3】评估时忘记 with torch.no_grad()

答案：C —— 显存/内存占用明显变大（计算图被保留）。
      评估不需要反向传播，却仍然构建并保留计算图，白白占内存；
      数据量大时可能直接 OOM。

      ★ 顺带一提：模型内部若写错了，还有可能误更新参数，
        所以评估前通常还会写 model.eval()。

--------------------------------------------------------------------------
【带走三句话】

  1. 五步顺序不能换：zero_grad → forward → loss → backward → step
  2. 梯度默认累加：每个 batch 开头必须 zero_grad()
  3. 评估不建图：with torch.no_grad() + model.eval()

遇到报错不要慌：先看最后一行错误类型 → 再找第一个指向自己代码的行号。
''')
